export const FailureCode = {
  INSUFFICIENT_FUNDS: 'INSUFFICIENT_FUNDS',
  REVERSAL_INSUFFICIENT_FUNDS: 'REVERSAL_INSUFFICIENT_FUNDS',
  CURRENCY_MISMATCH: 'CURRENCY_MISMATCH',
  WALLET_NOT_FOUND: 'WALLET_NOT_FOUND',
  WALLET_PLAYER_MISMATCH: 'WALLET_PLAYER_MISMATCH',
  PROVIDER_IDENTITY_MISMATCH: 'PROVIDER_IDENTITY_MISMATCH',
  REFERENCE_NOT_FOUND: 'REFERENCE_NOT_FOUND',
  REFERENCE_MISMATCH: 'REFERENCE_MISMATCH',
  INVALID_REFERENCE_KIND: 'INVALID_REFERENCE_KIND',
  REFERENCE_NOT_PROCESSED: 'REFERENCE_NOT_PROCESSED',
  ALREADY_REVERSED: 'ALREADY_REVERSED',
  AMOUNT_MISMATCH: 'AMOUNT_MISMATCH',
  DUPLICATE_EXTERNAL_TRANSACTION: 'DUPLICATE_EXTERNAL_TRANSACTION',
  IDEMPOTENCY_CONFLICT: 'IDEMPOTENCY_CONFLICT',
} as const;

export type FailureCode = (typeof FailureCode)[keyof typeof FailureCode];

const FAILURE_CODES: ReadonlySet<string> = new Set(Object.values(FailureCode));

export const isFailureCode = (value: unknown): value is FailureCode =>
  typeof value === 'string' && FAILURE_CODES.has(value);
